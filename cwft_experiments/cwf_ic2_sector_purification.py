"""
cwf_ic2_sector_purification.py -- the M2-GATE exploration of the "self-reference is
first" branch: is sector DEFINITENESS (the only physical relative-i variable, per
cwf_ic1_sector_gate) a collective phase transition or a local crossover?

Model (real-level, no complex structure assumed globally). N qubit-bubbles on a ring; each
bubble is R^4 with its own complex structure J_k. Joint state = real vector on (R^4)^{(x)N}.
Per layer, on every link (k,k+1):
   * a real orthogonal coupling gate: with probability eta a J-BREAKING gate (Haar SO(16):
     the substrate coupling ignores the bubbles' i's), otherwise a J-RESPECTING gate
     (generated by a real antisymmetric (J_k (x) 1) H_R, i.e. an ordinary complex-linear
     interaction seen at the real level; conserves the link charge Q_k = J_k (x) J_{k+1});
   * then, with probability p, a COMPARISON: projective measurement of Q_k = J_k (x) J_{k+1}
     (Born rule), the only process that makes a link's sector definite.
Observables: local definiteness m_k = |<Q_k>|, averaged over links, late layers and
trajectories; global sector distribution p(q) over the 2^{N-1} consistent sector labels
(entropy in bits / (N-1), and max_q p(q)); and the IC1 effective Renou witness
T(m) = 5.657 + 2.828 m per link (crosses the real bound 7.66 at m* = 0.708).

Gate question (SELFREF_FIRST_BRANCH.md sec 7 / M2-gate): a TRANSITION would show as a
sharpening of m(p) with N (a crossing point); a CROSSOVER shows as N-independent curves.
Scans: p in [0,1] at eta in {1.0, 0.5}; eta in [0,1] at p = 0.3. Seeded, CPU, minutes.
Writes ic2_sector_purification_results.json and fig_IC2_sector_purification.png.
"""
import json, os, time, itertools
import numpy as np
from scipy.linalg import expm

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = 20260827
rng = np.random.default_rng(SEED)

def real_form(M):
    A, B = np.real(M), np.imag(M)
    return np.block([[A, -B], [B, A]])

J4 = real_form(1j * np.eye(2))            # complex structure of one qubit-bubble (R^4)

def random_hermitian(n):
    M = rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n))
    return (M + M.conj().T) / 2

def gate_J_respecting(strength=0.8):
    HR = np.zeros((16, 16))
    for _ in range(3):
        HR += np.kron(real_form(random_hermitian(2)), real_form(random_hermitian(2)))
    HR += np.kron(real_form(random_hermitian(2)), np.eye(4)) + np.kron(np.eye(4), real_form(random_hermitian(2)))
    G = np.kron(J4, np.eye(4)) @ HR * strength
    return expm(G)                          # orthogonal, commutes with J(x)1 and 1(x)J

def gate_J_breaking():
    M = rng.normal(size=(16, 16))
    Q, R = np.linalg.qr(M)
    Q = Q @ np.diag(np.sign(np.diag(R)))
    if np.linalg.det(Q) < 0:
        Q[:, 0] *= -1
    return Q                                # Haar on SO(16)

def apply_pair(v, G, k, N):
    """Apply a 16x16 real gate on bubbles k, k+1 (mod N) of state tensor v (4,)*N."""
    j = (k + 1) % N
    w = np.moveaxis(v, [k, j], [0, 1]).reshape(16, -1)
    w = (G @ w).reshape((4, 4) + tuple(4 for _ in range(N - 2)))
    return np.moveaxis(w, [0, 1], [k, j])

def apply_Q(v, k, N):
    """Q_k v = (J_k (x) J_{k+1}) v."""
    j = (k + 1) % N
    w = np.tensordot(J4, v, axes=([1], [k])); w = np.moveaxis(w, 0, k)
    w = np.tensordot(J4, w, axes=([1], [j])); w = np.moveaxis(w, 0, j)
    return w

def measure_Q(v, k, N):
    Qv = apply_Q(v, k, N)
    p_minus = 0.5 * (1.0 - float(np.vdot(v, Qv)))
    if rng.random() < p_minus:
        w = (v - Qv) / 2.0
    else:
        w = (v + Qv) / 2.0
    return w / np.linalg.norm(w)

def local_definiteness(v, N):
    return np.array([abs(float(np.vdot(v, apply_Q(v, k, N)))) for k in range(N)])

def sector_distribution(v, N):
    """p(q) over sector labels q in {+-1}^N with prod q = (-1)^N (2^{N-1} of them)."""
    probs = []
    for q in itertools.product([-1, 1], repeat=N - 1):
        q = list(q) + [(-1) ** N * int(np.prod(q))]
        w = v
        for k in range(N):
            w = (w + q[k] * apply_Q(w, k, N)) / 2.0
        probs.append(float(np.vdot(w, w)))
    return np.array(probs)

def run(N, p, eta, layers, traj, init="indefinite"):
    ms, S_late, pmax_late = [], [], []
    for t in range(traj):
        v = np.zeros((4,) * N)
        if init == "indefinite":
            v[(0,) * N] = 1.0                              # real product basis vector: all links 50/50
        else:                                              # definite aligned (H2) start
            v[(0,) * N] = 1.0
            for k in range(N - 1):
                Qv = apply_Q(v, k, N); v = (v - Qv) / 2.0; v /= np.linalg.norm(v)
        mtraj = []
        for L in range(layers):
            offset = L % 2
            for k in range(offset, N, 2):
                if k + 1 >= N and N % 2 == 1 and offset == 1:
                    pass
                G = gate_J_breaking() if rng.random() < eta else gate_J_respecting()
                v = apply_pair(v, G, k % N, N)
            for k in range(N):
                if rng.random() < p:
                    v = measure_Q(v, k, N)
            if L >= layers // 2:
                mtraj.append(local_definiteness(v, N).mean())
        ms.append(np.mean(mtraj))
        pq = sector_distribution(v, N)
        pq = pq / pq.sum()
        S = -np.sum(pq[pq > 1e-15] * np.log2(pq[pq > 1e-15])) / max(N - 1, 1)
        S_late.append(S); pmax_late.append(pq.max())
    return dict(m=float(np.mean(ms)), m_sem=float(np.std(ms) / np.sqrt(traj)),
                S_sector=float(np.mean(S_late)), pmax=float(np.mean(pmax_late)))

def main():
    t0 = time.time()
    Ns = [4, 5, 6, 7, 8]
    ps = [0.0, 0.05, 0.1, 0.2, 0.3, 0.45, 0.6, 0.8, 1.0]
    etas_scan = [0.0, 0.1, 0.25, 0.5, 0.75, 1.0]
    layers, traj = 40, 8
    R = dict(seed=SEED, Ns=Ns, ps=ps, layers=layers, traj=traj, witness=dict(T0=5.657, slope=2.828, m_star=0.708),
             p_scan={}, eta_scan={}, h2_start={})
    print("cwf_ic2 -- sector definiteness: comparison (p) vs J-breaking scrambling (eta)\n")
    for eta in (1.0, 0.5):
        R["p_scan"][f"eta={eta}"] = {}
        for N in Ns:
            row = []
            for p in ps:
                r = run(N, p, eta, layers, traj)
                row.append(r)
            R["p_scan"][f"eta={eta}"][f"N={N}"] = row
            print(f"  eta={eta:.2f} N={N}: m(p) = " + " ".join(f"{r['m']:.3f}" for r in row)
                  + f"   [S_sec/(N-1) at p=0.3: {row[4]['S_sector']:.3f}]   ({time.time() - t0:.0f}s)")
    print()
    for N in (4, 6, 8):
        row = [run(N, 0.3, eta, layers, traj) for eta in etas_scan]
        R["eta_scan"][f"N={N}"] = row
        print(f"  p=0.30 N={N}: m(eta) = " + " ".join(f"{r['m']:.3f}" for r in row) + f"   ({time.time() - t0:.0f}s)")
    print()
    # H2 start: does an initially definite world stay definite? (eta=0: conserved; eta>0: decays unless compared)
    for eta in (0.0, 0.25, 1.0):
        r0 = run(6, 0.0, eta, layers, traj, init="definite")
        r1 = run(6, 0.3, eta, layers, traj, init="definite")
        R["h2_start"][f"eta={eta}"] = dict(p0=r0, p03=r1)
        print(f"  H2-start N=6 eta={eta:.2f}: m at p=0 -> {r0['m']:.3f};  at p=0.3 -> {r1['m']:.3f}")

    # --- gate diagnostics: sharpening with N?  crossing of curves?
    diag = {}
    for eta in (1.0, 0.5):
        curves = np.array([[r["m"] for r in R["p_scan"][f"eta={eta}"][f"N={N}"]] for N in Ns])
        spread = curves.max(axis=0) - curves.min(axis=0)          # N-spread at each p
        # p where m crosses m* (linear interpolation) per N
        pc = []
        for c in curves:
            idx = np.where(c >= 0.708)[0]
            if len(idx) == 0 or idx[0] == 0:
                pc.append(None); continue
            i = idx[0]; pc.append(float(ps[i - 1] + (0.708 - c[i - 1]) * (ps[i] - ps[i - 1]) / (c[i] - c[i - 1])))
        # slope of m(p) around the crossing, per N (a transition would steepen with N)
        slopes = [float(np.max(np.diff(c) / np.diff(ps))) for c in curves]
        diag[f"eta={eta}"] = dict(max_N_spread=float(spread.max()), p_cross_mstar=pc, max_slope_by_N=slopes)
        print(f"\n  eta={eta}: max spread of m(p) across N = {spread.max():.3f};  p where T(m) crosses 7.66, by N: "
              + ", ".join("None" if x is None else f"{x:.3f}" for x in pc)
              + f";  max slope by N: " + ", ".join(f"{s:.2f}" for s in slopes))
    R["gate_diagnostics"] = diag
    with open(os.path.join(HERE, "ic2_sector_purification_results.json"), "w") as f:
        json.dump(R, f, indent=2)
    print(f"\nWrote ic2_sector_purification_results.json  ({time.time() - t0:.0f}s)")
    plot(R)

def plot(R):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    ps, Ns = R["ps"], R["Ns"]
    fig, axes = plt.subplots(1, 3, figsize=(11, 3.4), dpi=300)
    for ax, eta in zip(axes[:2], (1.0, 0.5)):
        for N in Ns:
            row = R["p_scan"][f"eta={eta}"][f"N={N}"]
            ax.errorbar(ps, [r["m"] for r in row], yerr=[r["m_sem"] for r in row], marker="o", ms=3, lw=1, label=f"N={N}")
        ax.axhline(0.708, color="k", ls="--", lw=0.8)
        ax.text(0.98, 0.708 + 0.02, r"$m^*$: $T=7.66$", ha="right", fontsize=7)
        ax.set_xlabel("comparison rate $p$"); ax.set_ylabel(r"local definiteness $\bar m=\langle|\langle Q_k\rangle|\rangle$")
        ax.set_title(f"J-breaking fraction $\\eta={eta}$", fontsize=9); ax.set_ylim(-0.02, 1.05)
        ax.legend(fontsize=7, frameon=False)
    ax = axes[2]
    etas = [0.0, 0.1, 0.25, 0.5, 0.75, 1.0]
    for N in (4, 6, 8):
        row = R["eta_scan"][f"N={N}"]
        ax.errorbar(etas, [r["m"] for r in row], yerr=[r["m_sem"] for r in row], marker="s", ms=3, lw=1, label=f"N={N}")
    ax.axhline(0.708, color="k", ls="--", lw=0.8)
    ax.set_xlabel(r"J-breaking fraction $\eta$ (at $p=0.3$)"); ax.set_ylabel(r"$\bar m$")
    ax.set_title("scrambling erodes definiteness", fontsize=9); ax.set_ylim(-0.02, 1.05)
    ax.legend(fontsize=7, frameon=False)
    fig.suptitle("Sector definiteness under comparison vs J-breaking scrambling (ring of qubit-bubbles)", fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(HERE, "fig_IC2_sector_purification.png"))
    print("Wrote fig_IC2_sector_purification.png")

if __name__ == "__main__":
    main()
